import { Router } from 'express';
import { requireActiveAccount, requireAdmin, requireAuth } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import { asyncHandler } from '../utils/errors.js';
import { profileSchema, collaborationSchema, collaborationUpdateSchema, deliverableSchema, deliverableUpdateSchema, paymentSchema, invoiceSchema } from '../validators/schemas.js';
import { getMe, updateMe } from '../controllers/meController.js';
import { getDashboard } from '../controllers/dashboardController.js';
import { listCollaborations, createCollaboration, getCollaboration, updateCollaboration, deleteCollaboration } from '../controllers/collaborationController.js';
import { addDeliverable, updateDeliverable, deleteDeliverable } from '../controllers/deliverableController.js';
import { listPayments, createPayment, deletePayment, paymentHistory } from '../controllers/paymentController.js';
import { listInvoices, createInvoice, getInvoice, deleteInvoice, downloadInvoice } from '../controllers/invoiceController.js';
import { adminRouter } from './admin.js';
import { acknowledgeProductTour, createFeedback, recordFeedbackPrompt } from '../controllers/experienceController.js';
import { feedbackSchema, productTourSchema } from '../validators/feedbackSchemas.js';

export const apiRouter = Router();
apiRouter.get('/health', (_req, res) => res.json({ status: 'ok', service: 'collabdock-api' }));
apiRouter.use(requireAuth);
apiRouter.use('/admin', requireAdmin, adminRouter);
apiRouter.use(requireActiveAccount);
apiRouter.get('/me', asyncHandler(getMe));
apiRouter.patch('/me', validate(profileSchema), asyncHandler(updateMe));
apiRouter.post('/me/product-tour', validate(productTourSchema), asyncHandler(acknowledgeProductTour));
apiRouter.post('/me/feedback-prompt', asyncHandler(recordFeedbackPrompt));
apiRouter.post('/feedback', validate(feedbackSchema), asyncHandler(createFeedback));
apiRouter.get('/dashboard', asyncHandler(getDashboard));
apiRouter.route('/collaborations').get(asyncHandler(listCollaborations)).post(validate(collaborationSchema), asyncHandler(createCollaboration));
apiRouter.route('/collaborations/:id').get(asyncHandler(getCollaboration)).patch(validate(collaborationUpdateSchema), asyncHandler(updateCollaboration)).delete(asyncHandler(deleteCollaboration));
apiRouter.post('/collaborations/:id/deliverables', validate(deliverableSchema), asyncHandler(addDeliverable));
apiRouter.patch('/deliverables/:id', validate(deliverableUpdateSchema), asyncHandler(updateDeliverable));
apiRouter.delete('/deliverables/:id', asyncHandler(deleteDeliverable));
apiRouter.get('/payments', asyncHandler(listPayments));
apiRouter.get('/payments/history', asyncHandler(paymentHistory));
apiRouter.post('/collaborations/:id/payments', validate(paymentSchema), asyncHandler(createPayment));
apiRouter.delete('/payments/:id', asyncHandler(deletePayment));
apiRouter.route('/invoices').get(asyncHandler(listInvoices)).post(validate(invoiceSchema), asyncHandler(createInvoice));
apiRouter.route('/invoices/:id').get(asyncHandler(getInvoice)).delete(asyncHandler(deleteInvoice));
apiRouter.get('/invoices/:id/pdf', asyncHandler(downloadInvoice));
